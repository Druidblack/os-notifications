#!/usr/local/bin/python3
"""Deliver OPNsense notifications to MAX, Telegram and Gotify; stdlib only.

Configuration is generated by the OPNsense MVC template system and stored
in a root-private directory. This executable does not read config.xml.
"""
from __future__ import annotations

import argparse
import configparser
import datetime
import fcntl
import json
import os
from pathlib import Path
import re
import socket
import ssl
import sys
import syslog
import time
import urllib.error
import urllib.parse
import urllib.request

API_URLS = {
    "official": "https://platform-api2.max.ru/messages",
    "a161": "https://notify.a161.ru/messages",
}
DEFAULT_CONFIG = Path("/usr/local/etc/monit2max/settings.conf")
DEFAULT_LOCK = Path("/var/run/monit2max.lock")
DEFAULT_STATE = Path("/var/run/monit2max.last")
TIMEOUT = 12
MESSAGE_LIMIT = 4000
RECIPIENT_RE = re.compile(r"^-?[0-9]{1,19}$")
TOKEN_RE = re.compile(r"^[A-Za-z0-9_.~:\-]+$")


class NotifyError(Exception):
    """Expected configuration or delivery error (never include secrets)."""


def read_settings(path: Path = DEFAULT_CONFIG) -> dict[str, str]:
    parser = configparser.ConfigParser(interpolation=None)
    try:
        with path.open("r", encoding="utf-8") as handle:
            parser.read_file(handle)
        return dict(parser["general"])
    except (OSError, KeyError, configparser.Error) as error:
        raise NotifyError("Cannot read plugin configuration; save settings in OPNsense") from error


def validate_settings(settings: dict[str, str]) -> tuple[str, str, str, str, str]:
    # Missing provider is intentional for compatibility with 0.1.0 settings.
    provider = settings.get("provider", "official").strip() or "official"
    if provider not in API_URLS:
        raise NotifyError("Choose a valid connection method")
    token = settings.get("token", "").strip()
    kind = settings.get("recipienttype", "user").strip()
    recipient = settings.get("recipientid", "").strip()
    title = settings.get("title", "OPNsense Notifications").strip() or "OPNsense Notifications"
    if not token or not TOKEN_RE.fullmatch(token):
        raise NotifyError("Enter a valid MAX bot token")
    if kind not in ("user", "chat"):
        raise NotifyError("Choose a valid recipient type")
    if not RECIPIENT_RE.fullmatch(recipient) or int(recipient) == 0:
        raise NotifyError("Enter a valid numeric recipient ID")
    if kind == "user" and int(recipient) < 0:
        raise NotifyError("A user ID must be positive")
    if provider == "a161" and kind == "chat" and int(recipient) > 0:
        raise NotifyError("notify.a161.ru group and channel IDs must be negative")
    return provider, token, kind, recipient, title


TELEGRAM_CHAT_RE = re.compile(r"^(?:-?[0-9]{1,20}|@[A-Za-z][A-Za-z0-9_]{3,31})$")
TELEGRAM_TOKEN_RE = re.compile(r"^[0-9]+:[A-Za-z0-9_-]+$")


def enabled_channels(settings: dict[str, str]) -> list[str]:
    """Legacy installations without MaxEnabled keep MAX on by default."""
    if settings.get('enabled', '0').strip() != '1':
        return []
    channels = []
    if settings.get('maxenabled', '1').strip() == '1':
        channels.append('max')
    if settings.get('telegramenabled', '0').strip() == '1':
        channels.append('telegram')
    if settings.get('gotifyenabled', '0').strip() == '1':
        channels.append('gotify')
    return channels


def validate_telegram_settings(settings: dict[str, str]) -> tuple[str, str, str]:
    token = settings.get('telegramtoken', '').strip()
    chat_id = settings.get('telegramchatid', '').strip()
    topic = settings.get('telegramthreadid', '').strip()
    if not TELEGRAM_TOKEN_RE.fullmatch(token):
        raise NotifyError('Enter a valid Telegram bot token from BotFather')
    if not TELEGRAM_CHAT_RE.fullmatch(chat_id) or chat_id in ('0', '-0'):
        raise NotifyError('Enter a valid Telegram chat ID or public channel @username')
    if topic and (not topic.isdecimal() or not (0 < int(topic) < 2**63)):
        raise NotifyError('Telegram topic ID must be a positive number')
    return token, chat_id, topic


def send_telegram(token: str, chat_id: str, message: str, *, topic: str = '',
                  timeout: float = TIMEOUT) -> None:
    """Send plain text via official Telegram Bot API (no redirects / no HTML)."""
    if not TELEGRAM_TOKEN_RE.fullmatch(token):
        raise NotifyError('Invalid Telegram bot token')
    if not TELEGRAM_CHAT_RE.fullmatch(chat_id):
        raise NotifyError('Invalid Telegram chat ID')
    body = {'chat_id': chat_id, 'text': message[:MESSAGE_LIMIT]}
    if topic:
        if not topic.isdecimal() or int(topic) < 1:
            raise NotifyError('Invalid Telegram topic ID')
        body['message_thread_id'] = int(topic)
    request = urllib.request.Request(
        f'https://api.telegram.org/bot{token}/sendMessage',
        data=json.dumps(body, ensure_ascii=False).encode('utf-8'),
        headers={'Content-Type': 'application/json'}, method='POST')
    try:
        with urllib.request.build_opener(
                urllib.request.HTTPSHandler(context=ssl.create_default_context()),
                NoRedirects()).open(request, timeout=timeout) as response:
            if not 200 <= response.status < 300:
                raise NotifyError(f'Telegram API HTTP {response.status}')
            payload = json.load(response)
            if not isinstance(payload, dict) or payload.get('ok') is not True:
                raise NotifyError('Telegram API did not confirm delivery')
    except urllib.error.HTTPError as error:
        explanations = {400: 'invalid chat ID or request', 401: 'invalid bot token',
                        403: 'bot cannot post to the chat; start the bot or grant access',
                        404: 'bot API endpoint unavailable', 429: 'rate limit exceeded'}
        detail = explanations.get(error.code, 'temporary server problem' if error.code >= 500 else 'check bot and chat')
        raise NotifyError(f'Telegram HTTP {error.code}: {detail}') from None
    except urllib.error.URLError as error:
        if isinstance(error.reason, ssl.SSLCertVerificationError):
            raise NotifyError('Telegram TLS certificate verification failed') from None
        raise NotifyError('Unable to connect to Telegram; check DNS, WAN and TLS') from None
    except (TimeoutError, ssl.SSLError, OSError):
        raise NotifyError('Network or TLS error while sending to Telegram') from None
    except (ValueError, json.JSONDecodeError):
        raise NotifyError('Invalid Telegram API response') from None


GOTIFY_TOKEN_RE = re.compile(r"^[A-Za-z0-9_.~:\-]+$")


def validate_gotify_settings(settings: dict[str, str]) -> tuple[str, str, int]:
    """Validate the configured base URL; do not accept credentials or query strings."""
    raw_url = settings.get('gotifyserverurl', '').strip()
    token = settings.get('gotifytoken', '').strip()
    priority = settings.get('gotifypriority', '5').strip()
    if not raw_url or any(ord(char) < 33 or ord(char) == 127 for char in raw_url):
        raise NotifyError('Enter a valid Gotify server URL')
    try:
        url = urllib.parse.urlsplit(raw_url)
        if (url.scheme not in ('http', 'https') or not url.hostname or
                url.username is not None or url.password is not None or
                url.query or url.fragment or not url.netloc or
                url.port == 0):
            raise ValueError('invalid Gotify server URL')
        # Reject malformed authority including any path introduced before the host.
        if any(char in url.netloc for char in ('\\', '@')):
            raise ValueError('invalid Gotify server URL authority')
        if url.path.endswith('/message'):
            raise ValueError('Gotify server URL must be a base address')
    except ValueError:
        raise NotifyError('Enter the Gotify base URL (http:// or https://; no /message or credentials)') from None
    if not GOTIFY_TOKEN_RE.fullmatch(token):
        raise NotifyError('Enter a valid Gotify application token')
    if not priority.isdecimal() or not 0 <= int(priority) <= 10:
        raise NotifyError('Gotify priority must be a whole number from 0 to 10')
    # Keep optional reverse-proxy prefix; never put an application token in a URL.
    return raw_url.rstrip('/'), token, int(priority)


def send_gotify(server_url: str, token: str, message: str, *,
                title: str = 'OPNsense Notifications', priority: int = 5,
                timeout: float = TIMEOUT) -> None:
    """Post a JSON message to a self-hosted Gotify server."""
    base_url, token, priority = validate_gotify_settings({
        'gotifyserverurl': server_url, 'gotifytoken': token,
        'gotifypriority': str(priority),
    })
    data = json.dumps({'title': title[:80], 'message': message[:MESSAGE_LIMIT],
                       'priority': priority}, ensure_ascii=False).encode('utf-8')
    request = urllib.request.Request(
        base_url + '/message', data=data,
        headers={'Content-Type': 'application/json', 'X-Gotify-Key': token},
        method='POST')
    try:
        with urllib.request.build_opener(
                urllib.request.HTTPSHandler(context=ssl.create_default_context()),
                urllib.request.HTTPHandler(), NoRedirects()
        ).open(request, timeout=timeout) as response:
            if response.status not in (200, 201, 202):
                raise NotifyError(f'Gotify API HTTP {response.status}')
    except urllib.error.HTTPError as error:
        messages = {400: 'invalid request or message', 401: 'invalid application token',
                    403: 'application is not permitted to send messages',
                    404: 'server path not found; check the base URL',
                    413: 'message is too large', 429: 'rate limit exceeded'}
        reason = messages.get(error.code, 'temporary server problem' if error.code >= 500
                              else 'check server address and application token')
        raise NotifyError(f'Gotify HTTP {error.code}: {reason}') from None
    except urllib.error.URLError as error:
        if isinstance(error.reason, ssl.SSLCertVerificationError):
            raise NotifyError('Gotify TLS certificate verification failed; trust the server certificate') from None
        raise NotifyError('Cannot reach Gotify; check the server address, network and TLS') from None
    except (TimeoutError, ssl.SSLError, OSError):
        raise NotifyError('Network or TLS error while sending to Gotify') from None


def deliver(settings: dict[str, str], channel: str, message: str,
            *, timeout: float = TIMEOUT, rate_limit: bool = True) -> None:
    if channel == 'max':
        provider, token, kind, recipient, _ = validate_settings(settings)
        if rate_limit:
            enforce_rate_limit(min_interval=1.05 if provider == 'a161' else 0.6)
        send_message(token, kind, recipient, message, provider=provider, timeout=timeout)
    elif channel == 'telegram':
        token, chat_id, topic = validate_telegram_settings(settings)
        if rate_limit:
            enforce_rate_limit(min_interval=0.6)
        send_telegram(token, chat_id, message, topic=topic, timeout=timeout)
    elif channel == 'gotify':
        server_url, token, priority = validate_gotify_settings(settings)
        if rate_limit:
            enforce_rate_limit(min_interval=0.25)
        send_gotify(server_url, token, message,
                    title=settings.get('title', 'OPNsense Notifications'),
                    priority=priority, timeout=timeout)
    else:
        raise NotifyError('Unknown notification channel')


def event_message(title: str, environ: dict[str, str], *, test: bool = False) -> str:
    host = (environ.get("MONIT_HOST") or socket.gethostname()).strip()
    when = (environ.get("MONIT_DATE") or datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %z")).strip()
    if test:
        name = "Test notification"
        event = "Test"
        description = "Connection to the selected messenger from OPNsense is working."
    else:
        name = (environ.get("MONIT_SERVICE") or "Unknown service").strip()
        event = (environ.get("MONIT_EVENT") or "System event").strip()
        description = (environ.get("MONIT_DESCRIPTION") or "No additional details").strip()
    # Plain text on purpose: no user-controlled HTML or Markdown interpretation.
    message = (f"🔔 {title}\n\n"
               f"Host: {host}\n"
               f"Service: {name}\n"
               f"Event: {event}\n"
               f"Time: {when}\n\n"
               f"Details: {description}")
    # MAX limit is 4000 unicode codepoints, not UTF-8 bytes.
    return message[:MESSAGE_LIMIT]


def enforce_rate_limit(lock_path: Path = DEFAULT_LOCK, state_path: Path = DEFAULT_STATE,
                       min_interval: float = 0.6) -> None:
    """Serialize requests across script processes; a161 requires ~1 second spacing."""
    with lock_path.open("a+") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            try:
                last = float(state_path.read_text(encoding="ascii"))
            except (OSError, ValueError):
                last = 0.0
            time.sleep(max(0.0, min_interval - (time.time() - last)))
            state_path.write_text(f"{time.time():.6f}\n", encoding="ascii")
        finally:
            fcntl.flock(lock.fileno(), fcntl.LOCK_UN)


class NoRedirects(urllib.request.HTTPRedirectHandler):
    """Disallow following API redirects that could expose Authorization tokens."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def send_message(token: str, kind: str, recipient: str, message: str,
                 *, provider: str = "official", timeout: float = TIMEOUT) -> None:
    if provider not in API_URLS:
        raise NotifyError("Choose a valid connection method")
    if provider == "a161" and kind == "chat" and int(recipient) > 0:
        raise NotifyError("notify.a161.ru group and channel IDs must be negative")
    query = urllib.parse.urlencode({"user_id" if kind == "user" else "chat_id": recipient})
    body = json.dumps({"text": message}, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(
        f"{API_URLS[provider]}?{query}",
        data=body,
        headers={"Authorization": token, "Content-Type": "application/json"},
        method="POST",
    )
    service_name = "MAX API" if provider == "official" else "notify.a161.ru"
    try:
        # Never send credentials to a redirect destination, even on HTTPS.
        with urllib.request.build_opener(
            urllib.request.HTTPSHandler(context=ssl.create_default_context()),
            NoRedirects(),
        ).open(request, timeout=timeout) as response:
            if not 200 <= response.status < 300:
                raise NotifyError(f"{service_name} returned HTTP {response.status}")
    except urllib.error.HTTPError as error:
        # Never log response body, Authorization header, or URL credentials.
        explanations = {
            400: "invalid request or recipient ID",
            401: "invalid or expired access token",
            402: "payment or subscription required",
            403: "access forbidden; check service access, subscription and bot permissions",
            404: "recipient or API endpoint not found",
            409: "request conflicts with service state",
            413: "message is too large",
            429: "rate limit exceeded; try again later",
        }
        detail = explanations.get(error.code)
        if detail is None:
            detail = "service temporarily unavailable" if 500 <= error.code <= 599 else "check credentials and recipient"
        # Never echo arbitrary response bodies, which may include token or user data.
        raise NotifyError(f"{service_name} HTTP {error.code}: {detail}") from error
    except urllib.error.URLError as error:
        if isinstance(error.reason, ssl.SSLCertVerificationError):
            raise NotifyError("TLS certificate verification failed; check system trust certificates") from error
        raise NotifyError(f"Unable to connect to {service_name}; check DNS, WAN and TLS trust") from error
    except (TimeoutError, ssl.SSLError, OSError) as error:
        raise NotifyError(f"Network or TLS error while sending to {service_name}") from error


def run(*, config: Path = DEFAULT_CONFIG, test: bool = False,
        environ: dict[str, str] | None = None, rate_limit: bool = True,
        channel: str = 'max') -> dict[str, str]:
    settings = read_settings(config)
    enabled = settings.get('enabled', '0').strip() == '1'
    if not enabled and not test:
        raise NotifyError('Automatic notifications are disabled in plugin settings')
    if not test and channel not in enabled_channels(settings):
        raise NotifyError(f'{channel} notifications are disabled')
    message = event_message(settings.get('title', 'OPNsense Notifications'),
                            dict(os.environ) if environ is None else environ, test=test)
    deliver(settings, channel, message, rate_limit=rate_limit)
    name = {'telegram': 'Telegram', 'gotify': 'Gotify', 'max': 'MAX'}.get(channel, channel)
    if test:
        note = ' (automatic notifications are disabled)' if not enabled else ''
        return {'status': 'ok', 'message': f'Test message sent to {name}' + note}
    return {'status': 'ok', 'message': f'Notification sent to {name}'}


def main() -> int:
    parser = argparse.ArgumentParser(description="Send an OPNsense notification")
    parser.add_argument("--test", action="store_true", help="send an explicit MAX test message")
    parser.add_argument("--test-telegram", action="store_true", help="send an explicit Telegram test message")
    parser.add_argument("--test-gotify", action="store_true", help="send an explicit Gotify test message")
    args = parser.parse_args()
    try:
        result = run(test=args.test or args.test_telegram or args.test_gotify,
                     channel="gotify" if args.test_gotify else
                             "telegram" if args.test_telegram else "max")
    except NotifyError as error:
        # A simple, safe response for the OPNsense GUI and the system log.
        message = str(error)
        syslog.syslog(syslog.LOG_ERR, f"monit2max: {message}")
        print(json.dumps({"status": "failed", "message": message}))
        return 1
    except Exception:
        # Avoid leaking local secrets or traceback in a privileged UI response.
        syslog.syslog(syslog.LOG_ERR, "monit2max: unexpected error")
        print(json.dumps({"status": "failed", "message": "Unexpected notification error; check system log"}))
        return 1
    print(json.dumps(result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
